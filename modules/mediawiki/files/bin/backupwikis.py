#! /usr/bin/python3

import argparse
import html
import json
import os
import shutil
import subprocess
import sys
import time
from collections import Counter
from datetime import datetime
from pathlib import Path

import internetarchive

PHP = '/usr/bin/php'
PUBLIC_DBLIST = Path('/srv/mediawiki/cache/public.php')
# Inactive, closed and deleted wikis have not changed since their last backup
ACTIVE_DBLIST = Path('/srv/mediawiki/cache/active.php')
XML_DIR = Path('/opt/backups')
TMP_DIR = Path('/tmp')


def log(message: str) -> None:
    print(message, flush=True)


def get_wikis(dblist: Path) -> list[str]:
    if not dblist.is_file():
        log(f"File {dblist} not found")
        sys.exit(1)
    code = (
        '$list = include $argv[1];'
        "if ( is_array( $list['databases'] ?? false ) ) {"
        "    echo implode( PHP_EOL, array_keys( $list['databases'] ) );"
        '}'
    )
    output = subprocess.run(
        [PHP, '-r', code, '--', dblist],
        check=True, stdout=subprocess.PIPE, text=True,
    ).stdout
    return output.split()


def filter_wikis(wikis: list[str], start: str | None, end: str | None) -> list[str]:
    return [
        wiki for wiki in wikis
        if (not start or wiki >= start) and (not end or wiki < end)
    ]


def get_mw_version(wiki: str) -> str:
    version = subprocess.run(
        ['/usr/local/bin/getMWVersion', wiki],
        check=True, stdout=subprocess.PIPE, text=True,
    ).stdout.strip()
    if not version:
        raise ValueError(f'Could not determine the MediaWiki version of {wiki}')
    return version


def maintenance_script_command(mwversion: str, *args: str) -> list[str]:
    return [PHP, f'/srv/mediawiki/{mwversion}/maintenance/run.php', *args]


def run_maintenance_script(mwversion: str, *args: str) -> int:
    return subprocess.run(maintenance_script_command(mwversion, *args)).returncode


def get_site_info(wiki: str, mwversion: str) -> dict[str, str] | None:
    result = subprocess.run(
        maintenance_script_command(mwversion, 'MirahezeMagic:GetSiteInfo', '--json', '--wiki', wiki),
        stdout=subprocess.PIPE, text=True,
    )
    output = result.stdout.strip()
    # Warnings such as the deleted wiki notice come before the JSON on stdout.
    # This may happen due to a race condition where a wiki is deleted after it appears in the list of
    # wikis to archive.
    try:
        return json.loads(output.splitlines()[-1])
    except (IndexError, ValueError):
        log(f'Could not get site information for {wiki}: exit code {result.returncode}; {output[:200]}')
        return None


def build_metadata(wiki: str, mwversion: str, info: dict[str, str]) -> dict[str, str]:
    sitename = info.get('sitename') or ''
    url = info.get('url') or ''
    if sitename and url:
        title = f'{sitename} ({wiki}) - {url} - Miraheze'
        site = f'<a href="{html.escape(url)}">"{html.escape(sitename)}"</a>'
    else:
        title = f'{wiki} - Miraheze'
        site = f'"{html.escape(sitename or wiki)}"'

    metadata = {
        'mediatype': 'texts',
        'subject': ';'.join(filter(None, ['wiki', 'MediaWiki', 'Miraheze', sitename, wiki])),
        'description': f'A backup of the {site} wiki (database name: <b>{wiki}</b>) on <a href="https://miraheze.org">Miraheze</a>, self-generated by Miraheze itself every month to honor our <a href="https://meta.miraheze.org/wiki/Backups">backups commitment.</a>',
        'title': title,
        'collection': 'miraheze_stacks',
        'originalurl': url,
        'language': info.get('language') or '',
        'rights': info.get('license') or '',
        'scanner': f'MediaWiki {mwversion}',
    }
    # Leave out whatever GetSiteInfo could not tell us
    return {key: value for key, value in metadata.items() if value}


def upload(identifier: str, files: list[Path], metadata: dict[str, str]) -> None:
    upload_attempts = 3
    for attempt in range(1, upload_attempts + 1):
        try:
            item = internetarchive.get_item(identifier)
            item.upload(
                [str(file) for file in files], metadata=metadata, verbose=True, checksum=True,
                retries=5, retries_sleep=300,
            )
            return
        except Exception as e:
            if upload_attempts == attempt:
                raise
            # Catch other types of failures that slip through upload
            delay = 120 * attempt
            log(f'Upload to {identifier} failed ({e}), retrying in {delay} seconds...')
            time.sleep(delay)


def cleanup(wiki: str, paths: list[Path]) -> None:
    for path in paths:
        if path.exists():
            log(f'Deleting {path}...')
            path.unlink()
    # SwiftDump leaves its download directory behind if it fails before tar removes it
    shutil.rmtree(TMP_DIR / wiki, ignore_errors=True)


def backup_wiki(wiki: str, date: str, no_upload: bool = False) -> str:
    """Returns ok, partial (XML dump only) or failed (nothing uploaded)."""
    xml_path = XML_DIR / f'{wiki}-{date}.xml.gz'
    images_name = f'{wiki}-images-{date}.tar.gz'
    images_path = TMP_DIR / images_name

    try:
        mwversion = get_mw_version(wiki)
        log(f'{wiki} is running MediaWiki {mwversion}')

        log(f'Retrieving site information for {wiki}...')
        info = get_site_info(wiki, mwversion)
        if info is None:
            return 'failed'

        code = run_maintenance_script(
            mwversion, 'dumpBackup', '--wiki', wiki,
            '--output', f'gzip:{xml_path}', '--full', '--logs', '--uploads',
        )
        if code != 0:
            log(f'XML dump for {wiki} failed with exit code {code}')
            return 'failed'

        files = [xml_path]
        code = run_maintenance_script(mwversion, 'MirahezeMagic:SwiftDump', '--wiki', wiki, '--filename', images_name)
        if code == 0:
            files.append(images_path)
        else:
            log(f'Image dump for {wiki} failed with exit code {code}, uploading the XML dump only')

        if no_upload:
            log(f"Skipping upload for {wiki}, keeping {' '.join(map(str, files))}")
        else:
            upload(f'miraheze-wiki-{wiki}-{date}', files, build_metadata(wiki, mwversion, info))
            log(f'Upload for {wiki} completed!')
        return 'ok' if code == 0 else 'partial'
    except Exception as e:
        log(f'An error occurred during backup or upload for {wiki}: {e}')
        return 'failed'
    finally:
        if not no_upload:
            cleanup(wiki, [xml_path, images_path])


def logsalmsg(message: str) -> None:
    subprocess.run(['/usr/local/bin/logsalmsg', message])


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description='Back up all active public wikis to the Internet Archive.')
    parser.add_argument('--start', help='Only back up wikis at or after this db name')
    parser.add_argument('--end', help='Only back up wikis before this db name')
    parser.add_argument('--wiki', help='Only back up the specified wiki')
    parser.add_argument('--log', action='store_true', help='Log the start and end of the run to the SAL')
    parser.add_argument('--no-upload', action='store_true', help='Keep the dumps locally instead of uploading them')
    return parser.parse_args(argv)


def get_public_active_wikis() -> list[str]:
    active_wikis = set(get_wikis(ACTIVE_DBLIST))
    public_wikis = set(get_wikis(PUBLIC_DBLIST))
    return sorted(active_wikis.intersection(public_wikis))


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    wikis = get_public_active_wikis()
    wikis = filter_wikis(wikis, args.start, args.end)
    if args.wiki:
        wikis = [wiki for wiki in wikis if wiki == args.wiki]

    # puppet now requires a proxy for outbound internet connections
    os.environ['HTTPS_PROXY'] = 'http://bastion.fsslc.wtnet:8080'

    log(f'Backing up {len(wikis)} wikis.')

    if args.log:
        logsalmsg('AUTOMATIC: Archival of all public wikis to Internet Archive has begun...')

    statuses = {}
    for wiki in wikis:
        date = datetime.now().strftime('%Y%m%d')
        statuses[wiki] = backup_wiki(wiki, date, args.no_upload)
        log(f'Done with {wiki}: {statuses[wiki]}.')

    counts = Counter(statuses.values())
    failed = [wiki for wiki, status in statuses.items() if status == 'failed']
    summary = f"{counts['ok']} ok, {counts['partial']} without images, {counts['failed']} failed"
    log(f'Finished: {summary}')
    if failed:
        log(f"Failed wikis: {' '.join(failed)}")

    if args.log:
        logsalmsg(f'AUTOMATIC: Finished archival of all public wikis to Internet Archive ({summary})')

    if failed:
        sys.exit(1)
    else:
        sys.exit(0)


if __name__ == '__main__':
    main()
